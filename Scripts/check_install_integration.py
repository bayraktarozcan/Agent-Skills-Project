#!/usr/bin/env python3
"""Network integration checks for the real installer path.

Modes:
  default       one pinned repo: real clone, SHA check, real process_repo()
                install into a temp prefix, copy/provenance verification and a
                local-fixture collision install.
  --all         all pinned repos: compare live skill names and SHAs against
                SKILL-INVENTORY.json; removed skills and commit mismatches fail,
                new skills are reported as drift.
  --refresh     rebuild SKILL-INVENTORY.json from the current pinned commits.
  --selftest    offline detector checks.

The baseline inventory is a data layer projection, not a trust anchor: it is
regenerated by the weekly pin-refresh workflow so removals are visible in the
PR diff before merge.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import skills  # noqa: E402  (project module under test)

MANIFEST = ROOT / "SKILL-SPECIALIZATION.json"
INVENTORY = ROOT / "SKILL-INVENTORY.json"
DEFAULT_REPO = "expo/skills"
MIN_SKILLS = 20


def repo_subpath(repo: str) -> str:
    for category in skills.REPOS["categories"]:
        for entry in category["repos"]:
            if entry["repo"] == repo:
                return str(entry.get("subpath", ""))
    return ""


def pinned_repos() -> list[str]:
    return [
        str(entry["repo"])
        for category in skills.REPOS["categories"]
        for entry in category["repos"]
    ]


def manifest_names() -> set[str]:
    return set(json.loads(MANIFEST.read_text(encoding="utf-8"))["skills"].keys())


def load_inventory() -> dict[str, dict]:
    if not INVENTORY.is_file():
        return {}
    try:
        data = json.loads(INVENTORY.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data.get("repos", {})


def save_inventory(entries: dict[str, dict]) -> None:
    payload = {
        "version": "1.0.0",
        "generated": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "repos": entries,
    }
    INVENTORY.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
        encoding="utf-8", newline="\n",
    )


def commit_matches(actual: str, expected: str) -> bool:
    return bool(expected) and actual == expected


def missing_names(found: set[str], known: set[str]) -> list[str]:
    return sorted(found - known)


def snapshot(repo: str) -> tuple[str, set[str], list[str]]:
    """Real clone via the installer's own code path; return commit, skills, errors."""
    errors: list[str] = []
    ref = skills._repo_ref(repo)
    if not ref:
        return "", set(), ["missing commit pin"]
    tmpdir = Path(tempfile.mkdtemp(prefix="asp-integration-"))
    try:
        ok, detail = skills._clone_once(repo, repo_subpath(repo), tmpdir)
        if not ok:
            return "", set(), [f"clone failed: {detail}"]
        actual = skills._repo_commit(tmpdir)
        if not commit_matches(actual, ref):
            errors.append(f"commit mismatch: expected {ref}, got {actual or '-'}")
        subpath = repo_subpath(repo)
        source = tmpdir / subpath if subpath else tmpdir
        names: set[str] = set()
        for mdfile in sorted(source.rglob("SKILL.md")):
            if skills._source_verdict(mdfile, source, tmpdir) is not None:
                errors.append(f"unsafe source: {mdfile.name}")
                continue
            raw = mdfile.read_bytes()
            names.add(skills.valid_name(
                skills._frontmatter_name(raw.decode("utf-8", "replace"))
                or mdfile.parent.name
            ))
        return actual, names, errors
    finally:
        skills.cleanup(tmpdir)


def verify_real_install(repo: str, expected_count: int) -> list[str]:
    """Run the unmodified process_repo() into a temp prefix and audit the result."""
    errors: list[str] = []
    saved_dir = skills.SKILLS_DIR
    saved_provenance = skills._record_provenance
    entries: list[dict] = []
    with tempfile.TemporaryDirectory() as temp:
        skills.SKILLS_DIR = Path(temp) / "skills"
        skills._record_provenance = entries.append
        claims: dict[str, dict] = {}
        try:
            count, _fixes = skills.process_repo(repo, repo_subpath(repo), "en", claims)
        finally:
            skills.SKILLS_DIR = saved_dir
            skills._record_provenance = saved_provenance
        if count != expected_count:
            errors.append(f"installed {count} skills, source has {expected_count}")
        installed = sorted(
            p.name for p in (Path(temp) / "skills").iterdir() if p.is_dir()
        )
        if installed != sorted(claims):
            errors.append("installed folders and claim registry disagree")
        for name, claim in claims.items():
            target = Path(temp) / "skills" / name / "SKILL.md"
            if not target.is_file():
                errors.append(f"missing installed file: {name}")
                continue
            digest = hashlib.sha256(target.read_bytes()).hexdigest()
            if digest != claim["digest"]:
                errors.append(f"digest mismatch after install: {name}")
        records = [entry for entry in entries if "moved_from" not in entry]
        if len(records) < count:
            errors.append(f"only {len(records)} provenance records for {count} skills")
    return errors


def verify_collision() -> list[str]:
    """Real git clone of two local fixture repos through process_repo()."""
    errors: list[str] = []
    saved_clone = skills._clone_once
    saved_ref = skills._repo_ref
    saved_trust = skills._repo_trust
    saved_dir = skills.SKILLS_DIR
    saved_provenance = skills._record_provenance
    entries: list[dict] = []
    with tempfile.TemporaryDirectory() as temp:
        base = Path(temp)
        fixtures: dict[str, str] = {}
        for label, body in (("risk", "B"), ("trusted", "A")):
            source = base / label
            source.mkdir()
            (source / "SKILL.md").write_text(
                f"---\nname: demo\n---\n{body}\n", encoding="utf-8", newline="\n"
            )
            subprocess.run(["git", "init", "-q"], cwd=source, check=True)
            subprocess.run(["git", "add", "."], cwd=source, check=True)
            subprocess.run(
                ["git", "-c", "user.name=T", "-c", "user.email=t@example.com",
                 "commit", "-q", "-m", "fixture"], cwd=source, check=True,
            )
            fixtures[f"fixture/{label}"] = subprocess.check_output(
                ["git", "rev-parse", "HEAD"], cwd=source, text=True
            ).strip()

        def fake_clone(repo: str, subpath: str, target: Path) -> tuple[bool, str]:
            label = repo.split("/")[-1]
            result = subprocess.run(
                ["git", "clone", "-q", "--depth", "1", str(base / label), str(target)],
                capture_output=True, text=True,
            )
            return result.returncode == 0, result.stderr.strip()

        skills._clone_once = fake_clone
        skills._repo_ref = lambda repo: fixtures.get(repo, "")
        skills._repo_trust = lambda repo: (
            "curated" if repo.endswith("trusted") else "risk"
        )
        skills.SKILLS_DIR = base / "skills"
        skills._record_provenance = entries.append
        claims: dict[str, dict] = {}
        try:
            skills.process_repo("fixture/risk", "", "en", claims)
            skills.process_repo("fixture/trusted", "", "en", claims)
            canonical = (skills.SKILLS_DIR / "demo" / "SKILL.md").read_text(
                encoding="utf-8"
            )
            moved = (skills.SKILLS_DIR / "demo--fixture-risk" / "SKILL.md").read_text(
                encoding="utf-8"
            )
            if "\nA\n" not in canonical or "\nB\n" not in moved:
                errors.append("collision copies were not both preserved")
            if not any(entry.get("moved_from") == "demo" for entry in entries):
                errors.append("collision provenance record missing")
        finally:
            skills._clone_once = saved_clone
            skills._repo_ref = saved_ref
            skills._repo_trust = saved_trust
            skills.SKILLS_DIR = saved_dir
            skills._record_provenance = saved_provenance
    return errors


def selftest() -> int:
    if commit_matches("b" * 40, "a" * 40):
        print("FAIL selftest: wrong commit not detected")
        return 1
    print("PASS selftest: wrong commit detected")
    if missing_names({"present-skill", "new-skill"}, {"present-skill"}) != ["new-skill"]:
        print("FAIL selftest: new skill not detected")
        return 1
    print("PASS selftest: new skill detected")
    if missing_names({"old-skill"}, {"old-skill", "new-skill"}) != []:
        print("FAIL selftest: removed skill not detected")
        return 1
    print("PASS selftest: removed skill detected")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--all", action="store_true")
    parser.add_argument("--refresh", action="store_true")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()
    if args.selftest:
        return selftest()

    repos = pinned_repos()
    baseline = load_inventory()
    failures = 0

    if args.refresh:
        updated: dict[str, dict] = {}
        for repo in repos:
            commit, names, errors = snapshot(repo)
            if errors:
                failures += 1
                print(f"FAIL {repo}: " + "; ".join(errors))
                continue
            updated[repo] = {"commit": commit, "skills": sorted(names)}
            old = set(baseline.get(repo, {}).get("skills", []))
            added, removed = sorted(names - old), sorted(old - names)
            print(
                f"REFRESH {repo}: commit={commit} skills={len(names)} "
                f"added={len(added)} removed={len(removed)}"
            )
            if removed:
                print("  removed: " + ", ".join(removed[:8]))
        if not failures:
            save_inventory(updated)
            print(f"OK: inventory written with {len(updated)} repos")
        return 1 if failures else 0

    if args.all:
        for repo in repos:
            commit, names, errors = snapshot(repo)
            expected = baseline.get(repo)
            if expected is None:
                errors.append("missing inventory entry")
            else:
                old = set(expected.get("skills", []))
                removed = sorted(old - names)
                added = sorted(names - old)
                if removed:
                    errors.append("removed from source: " + ", ".join(removed[:8]))
                if added:
                    print(f"DRIFT {repo}: {len(added)} new skills not in inventory")
            if errors:
                failures += 1
                print(f"FAIL {repo}: " + "; ".join(errors))
            else:
                print(f"PASS {repo}: commit={commit} skills={len(names)}")
        return 1 if failures else 0

    commit, names, errors = snapshot(DEFAULT_REPO)
    known = manifest_names()
    unmapped = missing_names(names, known)
    if unmapped:
        print(f"DRIFT {DEFAULT_REPO}: {len(unmapped)} skills absent from manifest")
    if len(names) < MIN_SKILLS:
        errors.append(f"only {len(names)} SKILL.md files found")
    errors.extend(verify_real_install(DEFAULT_REPO, len(names)))
    errors.extend(verify_collision())
    if errors:
        failures += 1
        print(f"FAIL {DEFAULT_REPO}: " + "; ".join(errors))
    else:
        print(
            f"PASS {DEFAULT_REPO}: commit={commit} skills={len(names)} "
            "real install and collision verified"
        )
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
